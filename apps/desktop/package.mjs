import { execFileSync } from 'node:child_process';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const desktop = dirname(fileURLToPath(import.meta.url));
const repo = resolve(desktop, '../..');
const stage = join(desktop, 'dist', 'stage');
await rm(stage, { recursive: true, force: true });
execFileSync('pnpm', ['--filter', '@paso/desktop', 'deploy', '--legacy', '--prod', stage], { cwd: repo, stdio: 'inherit' });
await cp(join(desktop, 'main.mjs'), join(stage, 'main.mjs'));
await cp(join(desktop, 'preload.cjs'), join(stage, 'preload.cjs'));
await cp(join(repo, 'apps/web/dist'), join(stage, 'web'), { recursive: true });
await mkdir(join(stage, 'runtime'), { recursive: true });
await cp(process.execPath, join(stage, 'runtime/node'));
const manifest = JSON.parse(await readFile(join(stage, 'package.json'), 'utf8'));
manifest.main = 'main.mjs';
manifest.build = { electronVersion: JSON.parse(await readFile(join(repo, 'node_modules/electron/package.json'), 'utf8')).version, appId: 'org.paso.prototype', productName: 'Paso', asar: false, directories: { output: join(desktop, 'dist', 'release') }, mac: { target: ['dir'], identity: null }, files: ['**/*'] };
await writeFile(join(stage, 'package.json'), JSON.stringify(manifest, null, 2));
execFileSync(join(repo, 'node_modules/.bin/electron-builder'), ['--projectDir', stage, '--mac', 'dir', '--arm64'], { cwd: repo, stdio: 'inherit', env: { ...process.env, CSC_IDENTITY_AUTO_DISCOVERY: 'false' } });
